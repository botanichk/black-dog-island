# guard.sh - внешние вызовы смены темы под таймаутом.
#
# Зачем: смена темы зовёт dconf, gsettings и eww. Если D-Bus сессии не
# отвечает (на Void в виртуалке сервис dconf не поднимается), вызов висит
# вечно, а вместе с ним и остров: команду кнопки никто не завершит.
# Проверено на заглушке, которая спит: без таймаута theme/plank.sh не
# возвращался вовсе. Тот же капкан у eww: клиент читает ответ демона до
# упора (client.rs: do_server_call), и мёртвый демон вешает reload.
#
# Подключается так: . "$ROOT/theme/guard.sh"
# Зависимости: timeout из coreutils (есть в базовой системе).

# run_to <секунды> <команда...>: выполнить с таймаутом.
# Код 124 = сработал таймаут (так же отвечает сам timeout).
run_to() {
  _secs=$1
  shift
  if command -v timeout >/dev/null 2>&1; then
    timeout "$_secs" "$@"
  else
    "$@"
  fi
}

# timed_out <код>: true, если предыдущий run_to не уложился в таймаут.
timed_out() { [ "${1:-0}" -eq 124 ]; }
