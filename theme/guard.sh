# guard.sh - внешние вызовы смены темы под таймаутом.
#
# Зачем: смена темы зовёт dconf, gsettings и eww. Если D-Bus сессии не
# отвечает (на Void в виртуалке сервис dconf не поднимается), вызов висит
# вечно, а вместе с ним и остров: команду кнопки никто не завершит.
# Проверено на заглушке, которая спит: без таймаута theme/plank.sh не
# возвращался вовсе. Тот же капкан у eww: клиент читает ответ демона до
# упора (client.rs: do_server_call), и мёртвый демон вешает reload.
#
# Подключается так: . "$ROOT/theme/guard.sh"
# Зависимости: timeout из coreutils (есть в базовой системе).

# run_to <секунды> <команда...>: выполнить с таймаутом.
# Код 124 = сработал таймаут (так же отвечает сам timeout).
run_to() {
  _secs=$1
  shift
  if command -v timeout >/dev/null 2>&1; then
    timeout "$_secs" "$@"
  else
    "$@"
  fi
}

# timed_out <код>: true, если предыдущий run_to не уложился в таймаут.
timed_out() { [ "${1:-0}" -eq 124 ]; }

# lock_take <каталог-замка>: атомарно занять. 0 - взяли, 1 - занят другим.
# mkdir атомарен на всех ФС: из двух одновременных запусков каталог создаст
# ровно один. Замок на pid-файле (cat, потом >) так не умеет - оба читают
# "пусто" и оба пишут себя; проверено пятью параллельными запусками, файл
# взяли все пять. flock не годится: Plank перезапускается из theme/plank.sh
# и наследует открытый дескриптор, после чего замок заперт вечно
# (проверено: fuser показал plank).
# pid занявшего остаётся в LOCK_PID - для сообщения "уже идёт (pid N)".
lock_take() {
  _l=$1
  LOCK_PID=""
  if mkdir "$_l" 2>/dev/null; then
    printf '%s\n' "$$" > "$_l/pid" 2>/dev/null || true
    return 0
  fi
  # Замок остался от убитого процесса (kill -9, закрытый терминал).
  _p=$(cat "$_l/pid" 2>/dev/null || true)
  case "${_p:-}" in
    ''|*[!0-9]*) _p="" ;;
  esac
  if [ -n "$_p" ] && kill -0 "$_p" 2>/dev/null; then
    LOCK_PID=$_p
    return 1
  fi
  # rmdir, а не rm -rf: если сосед успел занять замок заново, rmdir не
  # сработает и мы честно выйдем, а не снимем чужой замок.
  # shortcut: два одновременных запуска поверх мёртвого замка могут оба
  # пройти (окно между rmdir и mkdir - микросекунды, только после kill -9).
  rm -f "$_l/pid" 2>/dev/null || true
  rmdir "$_l" 2>/dev/null || true
  mkdir "$_l" 2>/dev/null || return 1
  printf '%s\n' "$$" > "$_l/pid" 2>/dev/null || true
  return 0
}

# now_ms - миллисекунды от эпохи для замеров шагов темы.
# date +%s%3N есть только в GNU date (в Void и busybox его нет), поэтому
# считаем через python3: он и так обязателен для темы.
now_ms() {
  python3 -c 'import time; print(int(time.time() * 1000))' 2>/dev/null || echo 0
}
