#!/bin/sh
# lib/session.sh - охрана сеанса: проект живёт только в X11 + XFCE.
#
# Зачем: на ноутбуке владельца кроме XFCE есть сеанс Hyprland с Noctalia и
# своими виджетами. Если установщик, остров или автозапуск сработают там, они
# отключат чужую панель или поднимут второй Eww рядом с чужим. Поэтому все
# точки входа сначала спрашивают bdi_session_ok, и только потом что-то делают.
#
# Разрешено в любом сеансе: `check` (только читает) и `uninstall` (откат нужен
# как раз тогда, когда сеанс XFCE не поднялся, - см. часть D задания 17).
#
# Библиотека ничего не печатает и не меняет: решение принимает вызывающий.

# bdi_session_ok - 0, если сеанс поддерживается.
# Правила:
#   * Wayland - отказ всегда: остров на X11-окнах (dock, struts, xprop).
#   * XDG_CURRENT_DESKTOP задан и в нём нет XFCE - отказ (Hyprland, GNOME...).
#   * XDG_CURRENT_DESKTOP пуст - смотрим на DISPLAY: так бывает в скриптах,
#     запущенных из ssh/терминала без переменных рабочего стола.
bdi_session_ok() {
  case "${XDG_SESSION_TYPE:-}" in
    wayland) return 1 ;;
  esac

  case "${XDG_CURRENT_DESKTOP:-}" in
    *[Xx][Ff][Cc][Ee]*) return 0 ;;
    '')
      # Пустой рабочий стол: доверяем только живому X-дисплею.
      case "${DISPLAY:-}" in
        :*) return 0 ;;
        *) return 1 ;;
      esac ;;
    *) return 1 ;;
  esac
}

# bdi_session_name - что показать человеку: «wayland / Hyprland» и подобное.
bdi_session_name() {
  printf '%s / %s\n' "${XDG_SESSION_TYPE:-неизвестен}" "${XDG_CURRENT_DESKTOP:-неизвестен}"
}

# bdi_session_why - одна строка, почему сеанс не поддерживается.
bdi_session_why() {
  case "${XDG_SESSION_TYPE:-}" in
    wayland) printf 'сеанс Wayland: остров работает только на X11\n' ;;
    *)
      if [ -z "${DISPLAY:-}" ] && [ -z "${XDG_CURRENT_DESKTOP:-}" ]; then
        printf 'нет графического сеанса X11\n'
      else
        printf 'рабочий стол %s: проект сделан под XFCE\n' \
          "${XDG_CURRENT_DESKTOP:-неизвестен}"
      fi ;;
  esac
}

# bdi_same_display <DISPLAY процесса> - 0, если это наш X-дисплей.
# «:0» и «:0.0» - одна и та же сессия (так бывает: один процесс запущен
# из автозапуска, другой руками). Сравнение строкой убивало бы док соседа,
# поэтому номер экрана и хвост после точки отбрасываем: сессия одна на
# дисплее, второй пользователь сидит на ДРУГОМ дисплее (:1, :2).
bdi_same_display() {
  _a=${1:-}
  _b=${DISPLAY:-}
  # отбрасываем «.N» (номер экрана) и сравниваем дисплеи
  case "$_a" in *.*) _a=${_a%%.*} ;; esac
  case "$_b" in *.*) _b=${_b%%.*} ;; esac
  [ -n "$_a" ] && [ "$_a" = "$_b" ]
}
